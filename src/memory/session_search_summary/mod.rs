//! ## Audit findings (Task 1, 2026-05-01)
//!
//! - `WorkingMemoryAssembler::assemble` lives in `src/memory/assembler/mod.rs`
//!   and `HybridAssembler::assemble` in `src/memory/assembler/hybrid.rs`.
//!   Signature: `async fn assemble(&self, query: &str, agent_id: &str, session_id: Option<&str>, budget: AssemblyBudget) -> Result<MemoryEnvelope, AlephError>`.
//!   Adding a `filter: FactSourceFilter` parameter is the chosen extension.
//!
//! - `FactSource` enum at `src/memory/context/enums.rs:180`. Variants:
//!   - `Extracted` (default, LLM-extracted from conversation)
//!   - `Summary` (L1 Overview generated by `CompressionDaemon`)
//!   - `Document` (User-uploaded long document, Markdown-first)
//!   - `Manual` (User-created manually)
//!   - `SessionCompressed` (Compressed summary from `SessionCompactor` during active session)
//!   - `Synthesis` (Synthesized from cross-session pattern extraction during weekly dream cycles)
//!     `SessionCompressed` is the primary variant Spec B targets for filtering.
//!
//! - `SessionStore::search_messages` at `src/gateway/session_store/mod.rs:37`.
//!   Signature: `async fn search_messages(&self, query: &str, max_results: usize) -> Result<Vec<SearchHit>, SessionStoreError>`.
//!   Does NOT accept a `session_id` filter; search is global across all sessions.
//!
//! - Memory-fact write entry-point (CORRECTED 2026-05-01): Spec B writes to the
//!   Markdown-backed raw memory via `RawMemoryStore`, NOT to the `notes`/wiki layer
//!   and NOT to a `memory_facts` table (that name is aspirational in the plan).
//!
//!   * Trait method: `RawMemoryStore::insert_raw_memory(&self, raw: &RawMemory) -> Result<(), AlephError>`
//!     at `src/memory/store/raw_memory.rs:203`.
//!   * Markdown implementation: `src/memory/store/markdown/raw_memory.rs`.
//!     Bodies live in Markdown; the SQLite metadata index tracks work state.
//!   * Construction pattern (from `src/memory/session_compactor/mod.rs:503-506`,
//!     also lines 758-761 and 854-857):
//!     `RawMemory::new(content, RawMemorySource::SessionCompressed)
//!         .with_agent(...)
//!         .with_session(&session_id)
//!         .with_path(path)`.
//!   * For agents with a `capture_registry` configured, writes go through
//!     `insert_with_capture_filter` at `src/memory/extensions/insert_helper.rs:11`,
//!     which dispatches `on_capture` extensions then forwards to
//!     `RawMemoryStore::insert_raw_memory` only when the chain returns
//!     `CaptureDecision::Allow`. New writers should prefer this indirection
//!     when the registry is available.
//!
//!   Read-side audit (Step A, for Tasks 5 and 8):
//!   * Path-prefix lookup EXISTS:
//!     `RawMemoryStore::get_raw_by_path_prefix(path_prefix, agent_id, limit)`
//!     is implemented in `src/memory/store/markdown/raw_memory.rs`, using the
//!     metadata index to select paths within the agent scope and reading bodies
//!     from Markdown to enumerate `aleph://session/{sid}/d*` records.
//!   * Watermarked variant `get_raw_by_path_prefix_since(...since: i64)` also
//!     exists on `RawMemoryStore`.
//!   * Exact-path lookup does NOT exist (no `find_by_path` / `get_by_path`
