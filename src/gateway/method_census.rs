//! The registered-RPC-method → role-classification census (round-5 ⑥).
//!
//! `method_admin.rs`'s module doc described the audit as "re-run the
//! mechanical sweep and diff it against the two constant tables" — but the
//! sweep was PROSE: nobody re-ran it, and a runtime census is structurally
//! blind to the ~60% of methods registered via `register_handler!` after
//! `HandlerRegistry::new()`. The four times an ungated server-global verb
//! was found by hand (`dreaming.run_now`, `memory.compress`,
//! `memory.reembed`, `memory.reembed.cancel` — round-4 ⑥) were instances of
//! that blindness. This module is the sweep, made executable: it scrapes the
//! three registration patterns out of the production half of every source
//! file, classifies each receiver, and pins every method's current ruling.
//!
//! The rules that keep the scraper honest (each earned, not imagined):
//! - comment lines and the `#[cfg(test)]` half are dropped BEFORE scraping
//!   (`utils::source_scan::production_text` + `strip_comment_lines`), so a
//!   doc comment naming a method can neither satisfy nor break the census,
//!   and a CRLF checkout scans identically to LF. `production_text`, not
//!   `production_prefix`: a WHOLE-FILE test module carries no `#[cfg(test)]`
//!   of its own — its parent applies one — so the per-file cut hands the
//!   scraper 100% of it. This used to be handled by skipping
//!   `rel.ends_with("/tests.rs")`, which sees 77 of the 107 whole-file test
//!   modules under `src/` and misses the other 30 (判据 §5) — the count and
//!   its predicate live with the guard, in
//!   `utils::source_scan::production_text_empties_whole_file_test_modules_and_only_those`;
//! - a `.register(` call is an RPC registration iff its receiver is
//!   `handlers_mut()` or a `registry: &mut HandlerRegistry` — every other
//!   receiver must be named in [`KNOWN_NON_RPC_REGISTRIES`] with its reason,
//!   and an UNRECOGNISED receiver fails the census rather than being
//!   skipped (a scanner that skips what it doesn't recognise reports "all
//!   classified" over a shrinking sample);
//! - dynamic first arguments (`registry.register(method, …)`) are legal only
//!   as the `for method in […]` loops of the phase-1 registry, whose array
//!   literals ARE scraped; the same shape anywhere else fails the census.

