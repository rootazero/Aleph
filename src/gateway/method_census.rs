    /// Scrape every RPC method registration out of the production halves of
    /// `src/**/*.rs`. Returns the swept methods (with the file that
    /// registers them) and any registration-shaped call the receiver rules
    /// could not classify.
    fn sweep_rpc_methods() -> (BTreeMap<String, String>, Vec<String>) {
        fn walk(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
            let Ok(entries) = std::fs::read_dir(dir) else {
                return;
            };
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_dir() {
                    walk(&path, out);
                } else if path.extension().is_some_and(|e| e == "rs") {
                    out.push(path);
                }
            }
        }

        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut files = Vec::new();
        walk(&root, &mut files);

        let mut swept: BTreeMap<String, String> = BTreeMap::new();
        let mut unknown: Vec<String> = Vec::new();
        for file in files {
            let rel = file
                .strip_prefix(env!("CARGO_MANIFEST_DIR"))
                .unwrap_or(&file)
                .to_string_lossy()
                .replace('\\', "/");
            let Ok(text) = std::fs::read_to_string(&file) else {
                continue;
            };
            // Test-only files register freely; they are not producers. This
            // used to be `rel.ends_with("/tests.rs")`, which at `f84ad424a`
            // recognised 85 of the 104 file-backed `#[cfg(test)] mod X;`
            // declarations in the repo and missed `guard_tests.rs`,
            // `drift_tests.rs`, `dispatchable.rs` and 16 more (判据 §5).
            // `production_text` asks the parent instead, which is the fact.
            let prod = crate::utils::source_scan::strip_comment_lines(
                &crate::utils::source_scan::production_text(&file, &text),
            );
            let is_handler_registry_file =
                prod.contains("&mut HandlerRegistry") || rel == "src/gateway/handlers/mod.rs";

            // `register_handler!(server, "method"` and `reg!("method"` — both
            // macro forms always land in the gateway registry; `reg!` exists
            // only inside `builder/handlers/mcp.rs`.
            for seg in prod.split("register_handler!(").skip(1) {
                if let Some(m) = literal_after_paren(seg) {
                    swept.entry(m).or_insert(rel.clone());
                }
            }
            for seg in prod.split("reg!(").skip(1) {
                // Exclude `register_handler!(` which also contains `reg!(` —
                // the split above already owns it.
                let Some(m) = literal_after_paren(seg) else {
                    continue;
                };
                if rel != "src/bin/aleph-server/commands/start/builder/handlers/mcp.rs" {
                    unknown.push(format!(
                        "{rel}: reg!(\"{m}\") outside builder/handlers/mcp.rs"
                    ));
                } else {
                    swept.entry(m).or_insert(rel.clone());
                }
            }

            // `.register(` — literal and dynamic first arguments.
            let mut offset = 0;
            while let Some(rel_pos) = prod[offset..].find(".register(") {
                let pos = offset + rel_pos;
                let seg = &prod[pos + ".register(".len()..];
                offset = pos + 1;
                let before = &prod[..pos];
                let tail: String = before
                    .chars()
                    .rev()
                    .take(90)
                    .collect::<String>()
                    .chars()
                    .rev()
                    .collect();
                let receiver_is_handlers_mut = tail.trim_end().ends_with("handlers_mut()");
                let receiver_is_registry = tail.trim_end().ends_with("registry");
                // Macro-definition lines register nothing at runtime — the
                // `$` metavariable sits in the receiver OR the argument.
                if tail.contains('$') || seg.trim_start().starts_with('$') {
                    continue;
                }
                match literal_after_paren(seg) {
                    Some(m) => {
                        if receiver_is_handlers_mut
                            || (receiver_is_registry && is_handler_registry_file)
                        {
                            swept.entry(m).or_insert(rel.clone());
                        } else if KNOWN_NON_RPC_REGISTRIES.iter().any(|(f, _)| *f == rel) {
                            // Named non-RPC registry — skipped with a reason.
                        } else {
                            unknown.push(format!(
                                "{rel}: .register(\"{m}\") with an unrecognised receiver"
                            ));
                        }
                    }
                    None => {
                        // Dynamic first argument: legal only as the phase-1
                        // `for method in […]` loops, whose arrays are scraped
                        // separately below.
                        let dynamic_rpc = receiver_is_handlers_mut
                            || (receiver_is_registry && is_handler_registry_file);
                        if dynamic_rpc && rel != "src/gateway/handlers/mod.rs" {
                            unknown.push(format!(
                                "{rel}: dynamic .register( into an RPC registry — only the \
                                 phase-1 `for method in […]` loops may do that"
                            ));
                        }
                    }
                }
            }

            // The phase-1 placeholder loops register whole method arrays
            // (`canvas.*`, `wizard.*`) via a dynamic call — scrape the array
            // literals so those methods join the census too.
            if rel == "src/gateway/handlers/mod.rs" {
                let mut arr_rest = prod.as_str();
                while let Some(pos) = arr_rest.find("for method in [") {
                    let seg = &arr_rest[pos + "for method in [".len()..];
                    arr_rest = &seg[1..];
                    let Some(close) = seg.find(']') else { continue };
                    let body = &seg[..close];
                    let mut b = body;
                    while let Some(q) = b.find('"') {
                        let after = &b[q + 1..];
                        let Some(end) = after.find('"') else { break };
                        let lit = &after[..end];
                        if lit.contains('.') {
                            swept.entry(lit.to_string()).or_insert(rel.clone());
                        }
                        b = &after[end + 1..];
                    }
                }
            }
        }
        (swept, unknown)
    }

    /// The string literal immediately after the opening paren, if the first
    /// argument is a literal — `None` for composed/dynamic arguments.
    fn literal_after_paren(seg: &str) -> Option<String> {
        let trimmed = seg.trim_start();
        // `register_handler!(server, "…"` carries a receiver ident first.
        let after_receiver = if let Some(comma) = trimmed.find(',') {
            // Only strip a receiver when one is there: `register(` starts
            // with the literal directly.
            let (head, tail) = trimmed.split_at(comma);
            if head.chars().all(|c| c.is_alphanumeric() || c == '_') && !head.is_empty() {
                tail[1..].trim_start()
            } else {
                trimmed
            }
        } else {
            trimmed
        };
        let rest = after_receiver.strip_prefix('"')?;
        let close = rest.find('"')?;
        Some(rest[..close].to_string())
    }

